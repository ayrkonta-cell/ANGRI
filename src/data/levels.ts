import { BlockDef, LevelDef, MaterialType, PigDef, PigType } from '../types/game';
import { PIGS } from './characters';

function col(
  x: number,
  baseY: number,
  h: number,
  w = 18,
  material: MaterialType = 'wood',
): BlockDef {
  return { x, y: baseY + h / 2, w, h, material, shape: 'rect' };
}

function beam(
  x: number,
  baseY: number,
  w: number,
  h = 18,
  material: MaterialType = 'wood',
): BlockDef {
  return { x, y: baseY + h / 2, w, h, material, shape: 'rect' };
}

function crate(
  x: number,
  baseY: number,
  size = 38,
  material: MaterialType = 'wood',
): BlockDef {
  return { x, y: baseY + size / 2, w: size, h: size, material, shape: 'rect' };
}

function roof(
  x: number,
  baseY: number,
  w = 64,
  h = 44,
  material: MaterialType = 'wood',
): BlockDef {
  return { x, y: baseY + h / 2, w, h, material, shape: 'triangle' };
}

function boulder(x: number, baseY: number, size = 44): BlockDef {
  return { x, y: baseY + size / 2, w: size, h: size, material: 'boulder', shape: 'circle' };
}

function pig(x: number, baseY: number, type: PigType): PigDef {
  return { x, y: baseY + PIGS[type].radius, type };
}

